"""List what is missing for the built countries (built.txt). Writes gap_report.md. Needs network for the IMF series."""
import json, re, time, urllib.request
UA = {"User-Agent": "geopolitica-dashboard/1.0"}
NOW = time.gmtime().tm_year
IMFK = {"NGDP_RPCH": "gdpg", "LUR": "unemp", "PCPIPCH": "infl", "NGDPD": "gdp", "NGDPDPC": "gdppc", "PPPGDP": "ppp", "PPPPC": "pppc", "GGXWDG_NGDP": "debt", "GGXCNL_NGDP": "bal", "BCA_NGDPD": "ca"}
LAB = {"gdpg": "Real GDP growth", "unemp": "Unemployment", "infl": "Inflation", "gdp": "GDP (nominal)", "gdppc": "GDP per person", "ppp": "GDP (PPP)", "pppc": "GDP per person (PPP)", "debt": "Public debt", "bal": "Budget balance", "ca": "Current account", "gini": "Gini", "hdi": "HDI",
       "pop": "Population", "urban": "Urban share", "life": "Life expectancy", "fert": "Fertility", "voice": "Voice and accountability", "stab": "Political stability", "eff": "Government effectiveness", "law": "Rule of law", "corr": "Control of corruption"}
def get(u):
    for i in range(3):
        try: return json.load(urllib.request.urlopen(urllib.request.Request(u, headers=UA), timeout=40))
        except Exception: time.sleep(3)
built = [l.strip() for l in open("built.txt") if l.strip()]
ind = json.load(open("indicators.json")); trade = json.load(open("trade.json")); serv = json.load(open("services.json")); geo = json.load(open("geography.json"))
mx = json.load(open("macro_extra.json")); gx = json.load(open("gini_extra.json"))
imf = {}
for code in IMFK:
    j = get("https://www.imf.org/external/datamapper/api/v1/%s" % code)
    d = (j or {}).get("values", {}).get(code, {})
    for iso, ser in d.items():
        ys = [int(y) for y, v in ser.items() if v is not None and int(y) <= NOW]
        if ys: imf.setdefault(iso, set()).add(IMFK[code])
    print("imf", code, len(d), flush=True)
rows = {}
def add(k, what): rows.setdefault(k, []).append(what)
for k in built:
    r = ind.get(k, {}); have = imf.get(k, set())
    for f in IMFK.values():
        if f in have or r.get(f) or r.get(f + "2") or (mx.get(k, {}).get(f)): continue
        add(k, LAB[f])
    if not (r.get("gini") or r.get("gini2") or (gx.get(k, {}).get("v") is not None)):
        add(k, "Gini (no official estimate)")
    for f in ("hdi", "pop", "urban", "life", "fert", "voice", "stab", "eff", "law", "corr"):
        if not r.get(f): add(k, LAB[f])
    t = trade.get(k)
    if not t or not t.get("px", {}).get("top"): add(k, "Goods exports by product")
    if not t or not t.get("pm", {}).get("top"): add(k, "Goods imports by product")
    if not t or not t.get("cx", {}).get("top"): add(k, "Export partners")
    if not t or not t.get("cm", {}).get("top"): add(k, "Import partners")
    s = serv.get(k, {})
    if s.get("src") in (None, "none"): add(k, "Trade in services")
    g = geo.get(k, {})
    for f, lab in (("area", "Area"), ("hi", "Highest point"), ("lo", "Lowest point")):
        if not g.get(f): add(k, lab)
    for f, lab in (("lake", "Largest lake"), ("river", "Longest river")):
        if not g.get(f) or "nnamed" in str(g[f].get("n", "")): add(k, lab)
out = ["# Missing data for built countries", "", "Generated by gap_audit.py", ""]
for k in sorted(rows): out.append("- **%s**: %s" % (k, "; ".join(rows[k])))
out.append(""); out.append("%d of %d built countries have at least one gap." % (len(rows), len(built)))
open("gap_report.md", "w").write("\n".join(out)); print("\n".join(out))
